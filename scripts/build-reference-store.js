#!/usr/bin/env node
/**
 * Builds api/_lib/referenceStore.data.js: the approved reference data that ships WITH the app.
 *
 *   node scripts/build-reference-store.js            # writes the module
 *   node scripts/build-reference-store.js --check    # exits 1 if the committed module is out of date
 *
 * Only bundles listed in data/reference/approvals.json are included, and only when the bundle's CURRENT content
 * fingerprint equals the fingerprint that was reviewed. Re-running an importer or changing a parser therefore
 * removes the data from the app until it is reviewed again — it never silently inherits an old approval.
 *
 * Bundled data is read-only at runtime: user lookups never download a publication and never call a model.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { parseArgs } from 'node:util'
import { bundleContentHash } from './lib/bundleSql.js'

const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } })
const root = new URL('../', import.meta.url)
const approvals = JSON.parse(await readFile(new URL('data/reference/approvals.json', root), 'utf8'))

const PASSAGE_FIELDS = ['id', 'occupation_code', 'occupation_title', 'section_type', 'rank_band', 'components', 'heading', 'chapter', 'body', 'pdf_page_start', 'pdf_page_end', 'printed_page', 'sort_order', 'effective_from', 'effective_to', 'cumulative', 'skill_level']

export async function buildStore() {
  const sources = []
  const passages = []
  for (const a of approvals.approvals) {
    const bundle = JSON.parse(await readFile(new URL(`data/reference/bundles/${a.manifest_id}.bundle.json`, root), 'utf8'))
    const fp = bundleContentHash(bundle)
    if (fp !== a.fingerprint) {
      throw new Error(`${a.manifest_id}: the bundle changed since it was reviewed (fingerprint ${fp.slice(0, 12)} ≠ approved ${a.fingerprint.slice(0, 12)}). Review it again and update approvals.json.`)
    }
    const s = bundle.source
    sources.push({ ...s, review_status: 'approved', reviewed_by: a.reviewer, reviewed_at: a.reviewed_at, content_sha256: fp, import_batch: bundle.import_batch, review_scope: a.scope })
    for (const p of bundle.passages) {
      const row = { source_id: s.id, branch: p.branch, personnel_category: p.personnel_category }
      for (const f of PASSAGE_FIELDS) if (p[f] !== undefined && p[f] !== null && p[f] !== false) row[f] = p[f]
      passages.push(row)
    }
  }
  return `// GENERATED by scripts/build-reference-store.js — do not edit by hand.
// Approved reference data bundled with the app (see data/reference/approvals.json). Each source's content fingerprint
// was checked against the reviewed fingerprint when this file was built.
export const REFERENCE_STORE_BUILT_FROM = ${JSON.stringify(approvals.approvals.map(a => ({ manifest_id: a.manifest_id, fingerprint: a.fingerprint })))}
export const REFERENCE_STORE_SOURCES = ${JSON.stringify(sources)}
export const REFERENCE_STORE_PASSAGES = ${JSON.stringify(passages)}
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const body = await buildStore()
  const target = new URL('api/_lib/referenceStore.data.js', root)
  if (values.check) {
    const current = await readFile(target, 'utf8').catch(() => '')
    if (current !== body) { console.error('api/_lib/referenceStore.data.js is out of date. Run: node scripts/build-reference-store.js'); process.exit(1) }
    console.log('referenceStore.data.js is up to date')
  } else {
    await writeFile(target, body)
    console.log(`wrote api/_lib/referenceStore.data.js (${(body.length / 1e6).toFixed(2)} MB, ${approvals.approvals.length} sources)`)
  }
}
